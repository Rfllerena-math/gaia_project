# --- Constants ---
DEFAULT_API_URL = "https://agents-course-unit4-scoring.hf.space"
ATTACHMENTS_DIRECTORY = PROJECT_ROOT / "downloads"


def download_attachment(api_url: str, task_id: str, file_name: str) -> Path:
    """Download a task attachment into the project directory for the agent to inspect."""
    safe_name = Path(file_name).name
    if not safe_name:
        raise ValueError("The task attachment has no usable file name.")

    ATTACHMENTS_DIRECTORY.mkdir(exist_ok=True)
    destination = ATTACHMENTS_DIRECTORY / f"{task_id}_{safe_name}"
    response = requests.get(f"{api_url}/files/{task_id}", timeout=60)
    if response.status_code == 404:
        raise FileNotFoundError(
            f"The evaluation server lists '{safe_name}' for task {task_id}, but its "
            "official attachment endpoint currently does not serve that file."
        )
    response.raise_for_status()
    destination.write_bytes(response.content)
    return destination.relative_to(PROJECT_ROOT)

